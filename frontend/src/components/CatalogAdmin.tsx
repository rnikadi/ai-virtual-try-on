import { useEffect, useRef, useState } from "react";
import { api, type AdminProduct, type Category, type SamplePhoto } from "../api";
import { SamplePhotoCard } from "./SamplePhotoCard";

interface Props {
  categories: Category[];
  onChanged: () => void;
}

/**
 * The demo's product photos and sample shopper photos ship with the repo. This page shows the prompt
 * behind each one and lets you upload a replacement.
 */
export function CatalogAdmin({ categories, onChanged }: Props) {
  const [products, setProducts] = useState<AdminProduct[]>([]);
  const [samples, setSamples] = useState<SamplePhoto[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [copiedAll, setCopiedAll] = useState(false);

  useEffect(() => {
    Promise.all([api.adminProducts(), api.samples()])
      .then(([p, s]) => {
        setProducts(p);
        setSamples(s);
      })
      .catch((err: Error) => setError(err.message));
  }, []);

  function replace(updated: AdminProduct) {
    setProducts((list) => list.map((p) => (p.id === updated.id ? updated : p)));
    onChanged();
  }

  function replaceSample(updated: SamplePhoto) {
    setSamples((list) => list.map((s) => (s.subject === updated.subject ? updated : s)));
    onChanged();
  }

  async function copyAll() {
    const text = products.map((p) => `### ${p.sku} - ${p.name}\n${p.imagePrompt}`).join("\n\n");
    await navigator.clipboard.writeText(text);
    setCopiedAll(true);
    setTimeout(() => setCopiedAll(false), 2000);
  }

  return (
    <section className="admin">
      <div className="admin-head">
        <div>
          <h1>Demo images</h1>
          <p>
            These images ship with the app, generated by Gemini from the prompts shown. To use your own, upload a
            replacement; "Use original" switches back.
          </p>
        </div>
        <div className="admin-head-actions">
          <button className="button secondary" onClick={copyAll} disabled={products.length === 0}>
            {copiedAll ? "Copied" : "Copy all prompts"}
          </button>
        </div>
      </div>

      {error && (
        <p className="error" role="alert">
          {error}
        </p>
      )}

      <div className="admin-group">
        <h2>Sample shopper photos</h2>
        <p className="admin-note">
          Offered in the try-on panel for shoppers who don't want to upload their own photo. These are fictional people
          generated by AI.
        </p>
        <div className="sample-grid">
          {samples.map((s) => (
            <SamplePhotoCard key={s.subject} sample={s} onUpdated={replaceSample} />
          ))}
        </div>
      </div>

      {categories.map((c) => {
        const items = products.filter((p) => p.categoryId === c.id);
        if (items.length === 0) return null;
        return (
          <div key={c.id} className="admin-group">
            <h2>{c.name}</h2>
            {items.map((p) => (
              <ProductImageRow key={p.id} product={p} onUpdated={replace} />
            ))}
          </div>
        );
      })}
    </section>
  );
}

interface RowProps {
  product: AdminProduct;
  onUpdated: (p: AdminProduct) => void;
}

function ProductImageRow({ product, onUpdated }: RowProps) {
  const [working, setWorking] = useState<"upload" | "reset" | null>(null);
  const [copied, setCopied] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  async function upload(file: File | undefined) {
    if (!file) return;
    if (!["image/jpeg", "image/png", "image/webp"].includes(file.type)) {
      setError("Use a JPEG, PNG or WebP image.");
      return;
    }
    if (file.size > 10 * 1024 * 1024) {
      setError("That image is over 10 MB.");
      return;
    }
    await run("upload", () => api.uploadProductImage(product.id, file));
  }

  async function run(kind: "upload" | "reset", action: () => Promise<AdminProduct>) {
    setWorking(kind);
    setError(null);
    try {
      onUpdated(await action());
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setWorking(null);
    }
  }

  const busy = working !== null;

  async function copy() {
    await navigator.clipboard.writeText(product.imagePrompt);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  return (
    <article className="admin-row">
      <button
        type="button"
        className="admin-image"
        onClick={() => inputRef.current?.click()}
        onDragOver={(e) => e.preventDefault()}
        onDrop={(e) => {
          e.preventDefault();
          upload(e.dataTransfer.files[0]);
        }}
        disabled={busy}
        aria-label={`Upload image for ${product.name}`}
      >
        <img src={product.imageUrl} alt="" />
        {product.hasUploadedImage && <span className="badge ok">Your upload</span>}
      </button>

      <div className="admin-body">
        <div className="admin-title">
          <h3>{product.name}</h3>
          <span className="sku">{product.sku}</span>
        </div>
        <pre className="prompt">{product.imagePrompt}</pre>
        <div className="admin-actions">
          <button className="button secondary small" onClick={copy}>
            {copied ? "Copied" : "Copy prompt"}
          </button>
          <button className="button secondary small" onClick={() => inputRef.current?.click()} disabled={busy}>
            {working === "upload" ? "Uploading…" : "Upload replacement"}
          </button>
          {product.hasUploadedImage && (
            <button
              className="link-button"
              onClick={() => run("reset", () => api.resetProductImage(product.id))}
              disabled={busy}
            >
              Use original
            </button>
          )}
        </div>
        {error && (
          <p className="error" role="alert">
            {error}
          </p>
        )}
      </div>

      <input
        ref={inputRef}
        type="file"
        accept="image/jpeg,image/png,image/webp"
        hidden
        onChange={(e) => {
          upload(e.target.files?.[0]);
          e.target.value = "";
        }}
      />
    </article>
  );
}
